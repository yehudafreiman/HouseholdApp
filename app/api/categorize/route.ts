import { NextResponse } from "next/server";
import Anthropic from "@anthropic-ai/sdk";
import { createClient } from "@/lib/supabase/server";
import { SHOPPING_CATEGORIES, type ShoppingCategory } from "@/lib/shopping";

const anthropic = new Anthropic();

export async function POST(request: Request) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const body = await request.json().catch(() => null);
  const name = typeof body?.name === "string" ? body.name.trim() : "";

  if (!name) {
    return NextResponse.json({ error: "Missing item name" }, { status: 400 });
  }

  try {
    const systemPrompt = [
      "אתה מסווג מקצועי של פריטי קניות לסופרמרקט ישראלי טיפוסי, עבור רשימת " +
        "קניות משפחתית. המשתמשים מקלידים לעיתים קרובות מהר, תוך כדי קנייה " +
        "בפועל בסופר - ייתכנו שגיאות כתיב, השמטת אותיות, או ניסוח מקוצר. " +
        "התפקיד שלך הוא להבין את הכוונה הסבירה ביותר ולסווג לפיה, לא לוותר " +
        "בגלל אי-דיוק בכתיב.",

      "בהינתן שם של פריט, בחר בדיוק קטגוריה אחת מתוך הרשימה הבאה:\n" +
        SHOPPING_CATEGORIES.map((c) => `- ${c}`).join("\n"),

      "כללי סיווג, לפי סדר עדיפות:",

      "1. תיקון שגיאות: אם השם מכיל שגיאת כתיב, אות חסרה/עודפת, או ניסוח " +
        "לא מדויק - זהה את המוצר הקרוב ביותר בעברית וסווג לפיו. אל תבחר " +
        "'אחר' רק בגלל חוסר ודאות בכתיב; השתמש ב'אחר' רק כשהמוצר עצמו " +
        "(לא הכתיב שלו) לא שייך מבחינה עניינית לאף קטגוריה.",

      "2. ברירת מחדל = הצורה הטרייה והבסיסית: כשאין תיאור נוסף, ההנחה היא " +
        "שמדובר בצורה הטרייה/הגולמית של המוצר כפי שנמכרת בסופר, לא בצורה " +
        "מעובדת שלו - גם אם יש למוצר גם גרסה מיובשת/טחונה/משומרת. למשל " +
        "ירקות ופירות (עגבנייה, פלפל, בצל, שום, ג'ינג'ר) הם 'פירות וירקות' " +
        "כברירת מחדל, לא תבלינים או שימורים.",

      "3. מילות מפתח לעיבוד גוברות על ברירת המחדל וקובעות קטגוריה אחרת: " +
        "'טחון' / 'אבקת-' / 'יבש' על תבלין או עשב תיבול → 'תבלינים, רטבים " +
        "ושמנים' (למשל 'פלפל שחור', 'שום יבש', 'בצל מיובש', 'כורכום " +
        "טחון'). 'קפוא' → 'קפואים', ללא קשר לפריט הבסיסי (גם 'תירס קפוא' " +
        "או 'עוף קפוא'). 'בקופסה' / 'בצנצנת' / 'משומר' / 'בשימורים' → " +
        "'שימורים ואוכל מוכן'. מוצר שעבר עיבוד שהופך אותו למוצר שונה " +
        "לגמרי מהחומר הגלם (מיץ, ריבה, קטשופ, רסק) → הקטגוריה של המוצר " +
        "הסופי, לא של החומר הגלם ממנו הוא הוכן.",

      "4. עוגני התייחסות לקטגוריות שאינן מזון, שקל לבלבל ביניהן: " +
        "'כלי בית, מטבח וסוללות' - כלי בישול/אפייה/אחסון, כלים חשמליים " +
        "קטנים, סוללות, נורות (למשל סיר, מחבת, קערה, סוללות, נורה). " +
        "'טקסטיל, מצעים וביגוד בסיסי' - בדים/בגדים לשימוש חוזר: מגבות " +
        "(גם 'מגבת' ביחיד), מצעים, שמיכות, גרביים, ביגוד בסיסי - אלה " +
        "*לא* חד-פעמיים. 'מוצרים חד פעמיים' - נייר/פלסטיק לשימוש בודד " +
        "וזריקה: מגבונים, מפיות נייר, כלים חד-פעמיים, שקיות זבל, נייר " +
        "כסף/סרן. שימו לב: 'מגבת'/'מגבות' (טקסטיל) שונה מ'מגבונים' " +
        "(חד-פעמי) - למרות הדמיון בכתיב, אלה מוצרים שונים לגמרי. " +
        "'צעצועים, כלי כתיבה ומוצרי משרד' - משחקים, עפרונות/עטים, " +
        "מחברות, ציוד לבית ספר/משרד.",

      "5. שמות מותג/מסחריים: זהה איזה סוג מוצר המותג מייצג בפועל וסווג " +
        "לפי זה, לא לפי צליל השם עצמו. זה חל על כל תחום, כולל תרופות " +
        "ואלכוהול - לא רק מזון ומשקאות קלים. דוגמאות: מותגי משככי כאבים " +
        "(כמו 'אקמול', 'נורופן', 'אספירין') → 'בריאות, תרופות ותוספי " +
        "תזונה'. מותגי אלכוהול/ליקר (כמו 'אפרול', 'קמפרי', 'ג'ק דניאלס') " +
        "→ 'אלכוהול'. מותגי משקה קל (כמו 'קוקה קולה', 'ספרייט') → " +
        "'משקאות קרים'. אם שם המותג לא מוכר לך במפורש, שאל את עצמך באיזו " +
        "מחלקה בסופר מוצרים מהסוג הזה בדרך כלל נמכרים.",

      "6. עקרון-העל בכל מקרה גבולי: שאל את עצמך 'באיזו מחלקה/מדף בסופר " +
        "ישראלי טיפוסי הייתי מוצא את הפריט הזה בפועל?' ובחר את הקטגוריה " +
        "התואמת ביותר לתשובה הזו.",

      "7. 'אחר' הוא מוצא אחרון בלבד - שמור אותו למקרים שבהם המוצר באמת " +
        "לא שייך לאף אחת מהקטגוריות באופן עקרוני, לא כברירת מחדל לספק.",
    ].join("\n\n");

    const response = await anthropic.messages.create({
      model: "claude-haiku-4-5",
      max_tokens: 200,
      temperature: 0,
      system: systemPrompt,
      messages: [{ role: "user", content: name }],
      output_config: {
        format: {
          type: "json_schema",
          schema: {
            type: "object",
            properties: {
              category: { type: "string", enum: SHOPPING_CATEGORIES },
            },
            required: ["category"],
            additionalProperties: false,
          },
        },
      },
    });

    const block = response.content[0];
    const parsed =
      block?.type === "text" ? (JSON.parse(block.text) as { category?: string }) : null;
    const candidate = parsed?.category;
    const category: ShoppingCategory = (
      SHOPPING_CATEGORIES as readonly string[]
    ).includes(candidate ?? "")
      ? (candidate as ShoppingCategory)
      : "אחר";

    return NextResponse.json({ category });
  } catch (err) {
    console.error("categorize error", err);
    return NextResponse.json({ category: "אחר" satisfies ShoppingCategory });
  }
}
